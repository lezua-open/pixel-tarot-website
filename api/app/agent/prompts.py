# ── 单牌占卜 Prompt ───────────────────────────────────────────────────────────

def build_single_prompt(question: str, card_name: str, card_en: str, orient: str, meaning: str) -> str:
    """单牌占卜的 User Prompt"""
    return f"""【用户问题】{question}

【抽到的牌】{card_name}（{card_en}），{orient}
【牌义】{meaning}

请按以下结构回答：
1. 这张牌的核心含义（1-2句）
2. 对应用户问题的分析（2-3句）
3. 明确的建议和结论（1-2句）"""


# ── 多牌单张 Prompt ───────────────────────────────────────────────────────────

def build_card_prompt(question: str, card_name: str, card_en: str, orient: str, meaning: str, card_index: int) -> str:
    """多牌占卜中，单张牌的 User Prompt"""
    return f"""【用户问题】{question}

【当前牌】第{card_index + 1}张：{card_name}（{card_en}），{orient}
【牌义】{meaning}

这张牌的含义是什么？用1-2句话解释它的核心信息。
不要给出建议或结论，只解释这张牌代表什么。"""


# ── 综合解读 Prompt ───────────────────────────────────────────────────────────

def build_combined_prompt(question: str, cards_info: list[dict]) -> str:
    """三牌综合解读的 User Prompt"""
    card_lines = []
    for i, card in enumerate(cards_info):
        card_lines.append(
            f"第{i+1}张 {card['name']}（{card['orient']}）：{card['meaning']}\n解读：{card['reading']}"
        )
    cards_text = "\n\n".join(card_lines)

    return f"""【用户的问题】{question}

【三张牌及各自的解读】
{cards_text}

请完成以下任务：

第一步：直接回答用户的问题。用户问的是"{question}"，你需要给出明确的建议，并且说明为什么你会给出这个建议，如果不知道的话就告诉用户遵从内心的想法。

第二步：用三张牌的含义来支撑你的结论。说明为什么这三张牌指向这个答案，它们之间有什么关联。

第三步：给出1-2条用户现在可以立刻去做的具体行动建议。

注意：不要说空话套话，要针对用户的具体问题给出有针对性的回答。"""


# ── 批量解读 Prompt ──────────────────────────────────────────────────────────

def build_all_cards_prompt(question: str, cards_info: list[dict]) -> str:
    """一次性解读多张牌，用分隔符分隔每张牌的解读"""
    card_lines = []
    for i, card in enumerate(cards_info):
        card_lines.append(f"第{i+1}张：{card['name']}（{card['en']}），{card['orient']}，牌义：{card['meaning']}")
    cards_text = "\n".join(card_lines)

    return f"""【用户问题】{question}

【抽到的牌】
{cards_text}

请为每张牌写一段解读（2-3句），按顺序输出。每段解读必须结合用户的問題来分析这张牌的含义。

要求：
- 每张牌的解读用 ===CARD_SEPARATOR=== 分隔
- 不要写"第X张"之类的前缀，直接写解读内容
- 先说这张牌的核心含义，再说明它对用户的问题意味着什么
- 不要给最终建议或结论（综合解读时再说），但要点出这张牌与问题的关联
- 共输出{len(cards_info)}段解读，用{len(cards_info) - 1}个分隔符隔开

示例格式：
这张牌的核心含义是...。对于你的问题，它暗示...
===CARD_SEPARATOR===
这张牌代表...。在你的情况中，它说明...
===CARD_SEPARATOR===
这张牌象征...。就你的问题而言，它提醒..."""
